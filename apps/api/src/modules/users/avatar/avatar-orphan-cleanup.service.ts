import { Injectable, Logger } from '@nestjs/common';
import { Cron } from '@nestjs/schedule';

import { UsersRepository } from '../repositories/users.repository.js';
import { AvatarDiskStorage } from './avatar-disk.storage.js';

const GRACE_PERIOD_MS = 24 * 60 * 60 * 1000;
const MAX_CLEANUP_BATCH = 100;

/**
 * Filesystem and DB updates cannot share a transaction. Retry safe deletion
 * of unreferenced, aged files after service or storage failures.
 */
@Injectable()
export class AvatarOrphanCleanupService {
  private readonly logger = new Logger(AvatarOrphanCleanupService.name);

  constructor(
    private readonly usersRepository: UsersRepository,
    private readonly storage: AvatarDiskStorage,
  ) {}

  @Cron('0 4 * * *', { timeZone: 'Europe/Kyiv' })
  async cleanup(): Promise<void> {
    const cutoff = new Date(Date.now() - GRACE_PERIOD_MS);

    let keys: string[];
    try {
      keys = await this.storage.listOldKeys(cutoff, MAX_CLEANUP_BATCH);
    } catch {
      this.logger.warn('AVATAR_ORPHAN_SCAN_FAILED');
      return;
    }

    for (const key of keys) {
      try {
        // Recheck current references immediately before removing. Orphans
        // generated by failed DB commits or failed previous-file cleanup
        // are eligible only after the grace period.
        if (!(await this.usersRepository.isCurrentAvatar(key))) {
          await this.storage.remove(key);
        }
      } catch {
        // Continue with other files; tomorrow's run retries this candidate.
        // Do not log paths, guessed avatar keys or database error messages.
        this.logger.warn('AVATAR_ORPHAN_CLEANUP_FAILED');
      }
    }
  }
}
